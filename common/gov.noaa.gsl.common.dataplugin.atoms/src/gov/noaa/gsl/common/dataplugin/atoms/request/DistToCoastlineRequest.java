package gov.noaa.gsl.common.dataplugin.atoms.request;

import com.raytheon.uf.common.serialization.annotations.DynamicSerialize;
import com.raytheon.uf.common.serialization.annotations.DynamicSerializeElement;
import com.raytheon.uf.common.serialization.comm.IServerRequest;

/**
 * A request to retrieve the distance (in km) from a given lon/lat to the
 * nearest coastline, determined using that Stumpf dataset.
 *
 * <pre>
 *
 * SOFTWARE HISTORY
 * Date         Ticket#    Engineer          Description
 * ------------ ---------- ----------------- --------------------------
 * Dec 13, 2021        Robert.Weingruber     Initial Creation
 *
 * </pre>
 *
 * @author robert.weingruber
 * @version 1.0
 */
@DynamicSerialize
public class DistToCoastlineRequest implements IServerRequest {

    @DynamicSerializeElement
    private Float longitude;

    @DynamicSerializeElement
    private Float latitude;

    public DistToCoastlineRequest() {

    }

    public DistToCoastlineRequest(Float lon, Float lat) {
        this.longitude = lon;
        this.latitude = lat;
    }

    public Float getLongitude() {
        return longitude;
    }

    public void setLongitude(Float longitude) {
        this.longitude = longitude;
    }

    public Float getLatitude() {
        return latitude;
    }

    public void setLatitude(Float latitude) {
        this.latitude = latitude;
    }

    public void setLonLat(Float lon, Float lat) {
        this.longitude = lon;
        this.latitude = lat;
    }
}
